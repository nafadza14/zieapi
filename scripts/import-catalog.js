#!/usr/bin/env node
// Regenerate src/catalog/seed.js from a catalog capture (docs/evidence) produced
// during the REA study. Usage: node scripts/import-catalog.js path/to/zapi-catalog.json
import { readFileSync, writeFileSync } from "node:fs";

const EXCLUDE_CATEGORIES = new Set(["bypass-tools"]); // circumvention tools: intentionally not offered
const EXCLUDE_SCRAPERS = new Set(["ai:bypass-ai", "dev-tools:cf-sitekey"]); // AI-detector evasion, captcha sitekey extraction

const src = JSON.parse(readFileSync(process.argv[2], "utf8"));
const T = { s: "string", n: "number", i: "integer", b: "boolean", a: "array", o: "object" };
const scrapers = src.scrapers
  .filter((s) => !EXCLUDE_CATEGORIES.has(s.k.split(":")[0]) && !EXCLUDE_SCRAPERS.has(s.k))
  .map((s) => ({
    k: s.k,
    n: s.n,
    t: s.t ?? [],
    e: s.e.map(([path, method, summary, fields]) => {
      const [slug, ...rest] = path.split("/");
      return {
        s: slug,
        p: rest.length ? rest.join("/") : undefined,
        m: method === "GET" ? undefined : method,
        d: summary,
        f: fields.map(([name, t, req, def, en, loc, min, max]) => {
          const o = { name, type: T[t] ?? "string" };
          if (req) o.required = true;
          if (def !== undefined && def !== null) o.default = def;
          if (en) o.enum = en;
          if (loc === "b") o.in = "body";
          if (min !== undefined && min !== null) o.min = min;
          if (max !== undefined && max !== null) o.max = max;
          return o;
        }),
      };
    }),
  }));
const categories = src.categories.filter((c) => !EXCLUDE_CATEGORIES.has(c.slug)).map(({ slug, displayName, color }) => ({ slug, displayName, color }));
const out = `// GENERATED by scripts/import-catalog.js: catalog structure (sources, endpoint names and
// parameter schemas) observed on the public zapi.ink OpenAPI index during the REA study
// (${src.capturedAt}). Descriptions, icons and example data are NOT copied.
// Endpoints without a live implementation in src/scrapers/live are served by the upstream
// adapter (ZIE_UPSTREAM_URL) or reported as "planned".
export const SEED_CATEGORIES = ${JSON.stringify(categories)};
export const SEED_SCRAPERS = ${JSON.stringify(scrapers)};
`;
writeFileSync(new URL("../src/catalog/seed.js", import.meta.url), out);
console.log(`wrote ${scrapers.length} scrapers, ${scrapers.reduce((n, s) => n + s.e.length, 0)} endpoints, ${categories.length} categories`);
